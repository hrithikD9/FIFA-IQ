-- FIFA-IQ: external football API cache + request log
-- Run this in the Supabase SQL editor after supabase_schema.sql. Safe to re-run.
--
-- These tables are written only by the backend (service-role key), so RLS is
-- enabled with no policies: anon/authenticated clients cannot read or write them.

-- Cached raw provider responses (football-data.org, TheSportsDB).
create table if not exists public.api_cache (
    cache_key text primary key,
    provider text not null,
    payload jsonb not null,
    fetched_at timestamptz not null default now(),
    expires_at timestamptz not null
);

create index if not exists idx_api_cache_expires_at on public.api_cache (expires_at);

-- One row per outbound provider request, for admin API monitoring.
create table if not exists public.api_request_logs (
    id bigint generated by default as identity primary key,
    provider text not null,
    endpoint text not null,
    status_code integer,
    ok boolean not null,
    latency_ms integer,
    error text,
    created_at timestamptz not null default now()
);

create index if not exists idx_api_request_logs_created_at on public.api_request_logs (created_at desc);
create index if not exists idx_api_request_logs_provider on public.api_request_logs (provider, created_at desc);

alter table public.api_cache enable row level security;
alter table public.api_request_logs enable row level security;
