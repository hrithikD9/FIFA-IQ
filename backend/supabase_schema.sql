-- FIFA-IQ Supabase schema and seed data
-- Run this in the Supabase SQL editor.

create extension if not exists pgcrypto;

create table if not exists public.teams (
    id bigint generated by default as identity primary key,
    name text not null,
    league text,
    flag_url text,
    logo_url text,
    xg_avg double precision default 0 not null,
    possession_avg double precision default 0 not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint teams_name_unique unique (name)
);

alter table public.teams
    add column if not exists flag_url text;

-- Migration for databases created before the unique constraint existed.
-- Ensures teams.name has the teams_name_unique constraint so ON CONFLICT /
-- upsert logic does not raise PostgreSQL error 42P10. Safe to re-run.
do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'teams_name_unique'
          and conrelid = 'public.teams'::regclass
    ) then
        alter table public.teams
            add constraint teams_name_unique unique (name);
    end if;
end $$;

create table if not exists public.matches (
    id bigint generated by default as identity primary key,
    home_team_id bigint not null references public.teams (id) on delete cascade,
    away_team_id bigint not null references public.teams (id) on delete cascade,
    home_score integer,
    away_score integer,
    match_date timestamptz not null default now(),
    status text not null default 'scheduled',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint matches_different_teams check (home_team_id <> away_team_id),
    constraint matches_status_check check (status in ('scheduled', 'live', 'finished', 'postponed', 'cancelled')),
    constraint matches_score_check check (
        (home_score is null or home_score >= 0)
        and (away_score is null or away_score >= 0)
    )
);

create table if not exists public.predictions (
    id bigint generated by default as identity primary key,
    match_id bigint not null references public.matches (id) on delete cascade,
    win_prob_home double precision not null default 0,
    win_prob_away double precision not null default 0,
    draw_prob double precision not null default 0,
    underdog_insight text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint predictions_probability_range check (
        win_prob_home between 0 and 1
        and win_prob_away between 0 and 1
        and draw_prob between 0 and 1
    ),
    constraint predictions_probability_total check (
        abs((win_prob_home + win_prob_away + draw_prob) - 1.0) <= 0.01
    )
);

-- Existing databases may still have the original global match_id uniqueness.
alter table public.predictions
    drop constraint if exists predictions_match_id_key;

create index if not exists idx_matches_home_team_id on public.matches (home_team_id);
create index if not exists idx_matches_away_team_id on public.matches (away_team_id);
create index if not exists idx_matches_match_date on public.matches (match_date desc);
create index if not exists idx_predictions_match_id on public.predictions (match_id);

-- Ensure predictions carries a user_id column so rows are owned by the user who
-- created them. Required by the backend /save, /history, /generate endpoints and by
-- the user-scoped RLS policies below. References auth.users and cascades on delete.
alter table public.predictions
    add column if not exists user_id uuid references auth.users (id) on delete cascade;

create index if not exists idx_predictions_user_id on public.predictions (user_id);
create unique index if not exists idx_predictions_user_match_unique
    on public.predictions (user_id, match_id);

alter table public.teams enable row level security;
alter table public.matches enable row level security;
alter table public.predictions enable row level security;

drop policy if exists "teams_select_public" on public.teams;
create policy "teams_select_public"
on public.teams
for select
to anon, authenticated
using (true);

drop policy if exists "matches_select_public" on public.matches;
create policy "matches_select_public"
on public.matches
for select
to anon, authenticated
using (true);

drop policy if exists "predictions_select_public" on public.predictions;
drop policy if exists "predictions_select_own" on public.predictions;
create policy "predictions_select_own"
on public.predictions
for select
to authenticated
using (auth.uid() = user_id);

-- User-scoped write policies: an authenticated user may only insert, update, or
-- delete prediction rows they own (auth.uid() = user_id). Each statement is
-- preceded by DROP POLICY IF EXISTS so re-running this script is fully idempotent.
drop policy if exists "predictions_insert_own" on public.predictions;
create policy "predictions_insert_own"
on public.predictions
for insert
to authenticated
with check (auth.role() = 'authenticated' and auth.uid() = user_id);

drop policy if exists "predictions_update_own" on public.predictions;
create policy "predictions_update_own"
on public.predictions
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "predictions_delete_own" on public.predictions;
create policy "predictions_delete_own"
on public.predictions
for delete
to authenticated
using (auth.uid() = user_id);

